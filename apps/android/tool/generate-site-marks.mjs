// Reuse the original Web host map and pinned CC0 Simple Icons artwork.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
const web = new URL('../../../packages/client/ui-primitives/', import.meta.url)
const require = createRequire(new URL('package.json', web))
const icons = require('simple-icons')
const source = readFileSync(new URL('src/SiteGlyph.tsx', web), 'utf8')
const entries = [...source.matchAll(/'([^']+)': (si\w+),/g)]
if (!entries.length) throw new Error('Web site host map was not found')
const names = [...new Set(entries.map((entry) => entry[2]))]
const output = [
  '// Generated by tool/generate-site-marks.mjs from Web SiteGlyph.tsx.',
  '// Artwork: simple-icons (CC0-1.0); monochrome site marks, not app icons.',
  'const chatSitePaths = <String, String>{',
  ...entries.map(([, host, name]) => `  '${host}': _${name},`),
  '};', '',
  ...names.map((name) => {
    if (!icons[name]?.path) throw new Error(`Missing pinned artwork: ${name}`)
    return `const _${name} = '${icons[name].path}';`
  }), '',
].join('\n')
writeFileSync(new URL('../lib/chat_site_marks.g.dart', import.meta.url), output)
