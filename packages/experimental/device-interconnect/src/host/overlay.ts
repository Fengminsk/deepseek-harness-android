/**
 * The remote-host overlay this bundle generates on every child start.
 *
 * The overlay patches the `remote-host` row the remote host's own bundle
 * inserts: a matching id replaces that row's complete config, so every field
 * the Host config controls is restated here.
 * @module @deepseek-ai/dsh-device-interconnect/host/overlay
 */

import { mkdir, rename, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import type { DeviceInterconnectConfig } from '../types.ts'
import { OVERLAY_FILE_NAME } from './config.ts'

/**
 * Render the YAML overlay that configures the `remote-host` row.
 *
 * Values are emitted as JSON scalars, which are valid YAML, so a host name
 * containing `:` or `#` cannot change the document structure.
 * @param config - configuration the child must apply.
 * @returns the overlay document, newline-terminated.
 */
export function renderOverlay(config: DeviceInterconnectConfig): string {
  const { host, pairing } = config
  return [
    '# Generated by the Device Interconnect bundle from its Settings page.',
    '# Every child start rewrites this file; edit the Settings page instead.',
    '- id: remote-host',
    '  config:',
    `    enabled: true`,
    `    port: ${String(host.port)}`,
    `    host: ${JSON.stringify(host.host)}`,
    `    publicHost: ${JSON.stringify(host.publicHost)}`,
    `    publicOrigin: ${JSON.stringify(host.publicOrigin)}`,
    `    discoveryEnabled: ${String(host.discoveryEnabled)}`,
    `    discoveryPort: ${String(host.discoveryPort)}`,
    `    pagesEnabled: ${String(host.pagesEnabled)}`,
    `    pagesPort: ${String(host.pagesPort)}`,
    `    pairingTtlMs: ${String(pairing.pairingTtlMs)}`,
    `    pairingLongTerm: ${String(pairing.longTerm)}`,
    // The runtime row is also inserted by the remote-host profile; a patch
    // replaces that row's complete config, so `platform: desktop` (set by the
    // profile patch) must be restated next to the 2 GiB attachment limit.
    '- id: android-runtime',
    '  config:',
    '    platform: desktop',
    '    attachmentFileMaxBytes: 2147483648',
    '',
  ].join('\n')
}

/**
 * Absolute path of the generated overlay inside the bundle's data directory.
 * @param dataDir - bundle data directory.
 * @returns the overlay path passed to the child's `--patch`.
 */
export function overlayPath(dataDir: string): string {
  return join(dataDir, OVERLAY_FILE_NAME)
}

/**
 * Write the overlay atomically.
 * @param file - target overlay path.
 * @param config - configuration the child must apply.
 * @returns completion once the rename finished.
 */
export async function writeOverlay(file: string, config: DeviceInterconnectConfig): Promise<void> {
  await mkdir(dirname(file), { recursive: true })
  const temporary = `${file}.${String(process.pid)}.tmp`
  try {
    await writeFile(temporary, renderOverlay(config), 'utf8')
    await rename(temporary, file)
  } catch (error) {
    await rm(temporary, { force: true })
    throw error
  }
}
