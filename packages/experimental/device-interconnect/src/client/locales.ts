/**
 * Translate one diagnostic into display copy: known codes use the dictionary,
 * and an unknown code falls back to the server's message.
 * @param t - the page's locale reader.
 * @param diagnostic - code and fallback message from the Host.
 * @returns display text.
 */
export function diagnosticText(
  t: (key: DeviceInterconnectLocaleKey, params?: Record<string, string | number>) => string,
  diagnostic: Diagnostic,
): string {
  const key = DIAGNOSTIC_KEYS[diagnostic.code]
  return key === undefined ? diagnostic.message || t('errorUnknown') : t(key)
}
